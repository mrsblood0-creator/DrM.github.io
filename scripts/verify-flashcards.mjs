import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const elements=new Map();
const get=s=>{if(!elements.has(s))elements.set(s,{innerHTML:'',value:'all',hidden:false,addEventListener(){}});return elements.get(s)};
const window={LIBRARY:{videos:[],courses:[],flashcards:[]}};
vm.runInNewContext(fs.readFileSync('flashcards.js','utf8'),{window,document:{querySelector:get,addEventListener(){}},location:{hash:''},localStorage:{getItem(){return null}},setInterval(){},console});
const {schedule,parseCSV}=window.FlashcardScheduler;
const now=1000000,day=86400000,card={stage:'new',due:0,interval:0,ease:2.5,reps:0,lapses:0};
assert.equal(schedule(card,1,now).due,now+60000);
assert.equal(schedule(card,2,now).due,now+360000);
const learning=schedule(card,3,now);
assert.equal(learning.stage,'learning');assert.equal(learning.due,now+600000);
assert.equal(schedule(learning,3,now).interval,1);
assert.equal(schedule(card,4,now).interval,4);
const review={...card,stage:'review',interval:10};
assert.equal(schedule(review,1,now).lapses,1);
assert.equal(schedule(review,2,now).interval,12);
assert.equal(schedule(review,3,now).interval,25);
assert.equal(schedule(review,4,now).interval,33);
const csv=parseCSV('Front,Back\r\n"Question, with comma","Answer with ""quotes""\nand newline"');
assert.equal(csv[1][0],'Question, with comma');assert.equal(csv[1][1],'Answer with "quotes"\nand newline');
assert.throws(()=>parseCSV('"unclosed'));
console.log('PASS: all four flashcard ratings, learning graduation, lapse handling and CSV quoting.');
const actual={window:{}};
vm.runInNewContext(fs.readFileSync('library-data.js','utf8'),actual);
vm.runInNewContext(fs.readFileSync('flashcards.js','utf8'),{window:actual.window,document:{querySelector:get,addEventListener(){}},location:{hash:''},localStorage:{getItem(){return null}},setInterval(){},console});
for(const lecture of actual.window.LIBRARY.videos){
 actual.window.renderFlashcards(lecture.id);
 assert.equal(get('#flash-lecture').value,lecture.id);
 assert.equal(get('#flash-course').value,'all');
 assert.equal(get('#flash-subject').value,'all');
 assert(get('#flash-lecture-context').innerHTML.includes('#lecture/'+lecture.id));
}
console.log('PASS: every lecture flashcard deep link selects its lecture and clears conflicting filters.');
